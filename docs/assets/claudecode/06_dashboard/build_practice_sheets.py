def verify(df):
    """사건로그에 적은 수치가 매출데이터와 맞는지 몇 가지를 출력한다."""
    df = df.copy()
    df['ym'] = df['날짜(YYYY-MM)'].astype(str).str[:7]
    sm = df.drop_duplicates(['매장명', 'ym']).merge(
        df.groupby(['매장명', 'ym'])['매출액(만원)'].sum().rename('매출합'), on=['매장명', 'ym'])
    chk = [
        ('홍대 2020-04 이익률', sm[(sm.매장명 == '서울 홍대점') & (sm.ym == '2020-04')]['영업이익률(%)'].iloc[0], 5.8),
        ('앱 비중 2021-01', round(sm[sm.ym == '2021-01']['자사앱주문비중'].mean(), 3), 0.095),
        ('홀 비중 2022-01', round(sm[sm.ym == '2022-01']['홀_주문비중'].mean(), 2), 0.41),
        ('플랫폼수수료 2024-11', round(sm[sm.ym == '2024-11']['플랫폼수수료(만원)'].mean()), 790),
        ('신메뉴 2026-03', round(sm[sm.ym == '2026-03']['신메뉴매출비중'].mean(), 2), 0.13),
        ('홍대 2026-04 클레임', round(sm[(sm.매장명 == '서울 홍대점') & (sm.ym == '2026-04')]['클레임건수'].iloc[0]), 87),
        ('제주 2026-04 이익률', round(sm[(sm.매장명 == '제주 연동점') & (sm.ym == '2026-04')]['영업이익률(%)'].iloc[0], 1), 4.2),
        ('제주 B 개월', int((sm[sm.매장명 == '제주 연동점']['위생검사결과'] == 'B').sum()), 60),
        ('둔산 2026-01 행수', int(((df.매장명 == '대전 둔산점') & (df.ym == '2026-01')).sum()), 12),
        ('신메뉴 2026-06', round(sm[sm.ym == '2026-06']['신메뉴매출비중'].mean(), 2), 0.12),
        ('배달 비중 증가 2026-07', round(sm[sm.ym == '2026-07']['배달_주문비중'].mean() - sm[sm.ym == '2026-06']['배달_주문비중'].mean(), 2), 0.04),
        ('제주 2026-08 매출합', round(sm[(sm.매장명 == '제주 연동점') & (sm.ym == '2026-08')]['매출합'].iloc[0]), 8474),
    ]
    ok = True
    for name, got, want in chk:
        flag = 'OK' if abs(float(got) - float(want)) < 0.06 * max(1, abs(float(want))) else 'MISMATCH'
        ok &= flag == 'OK'
        print(f'  [{flag}] {name}: 데이터 {got} / 사건로그 {want}')
    return ok


def style_sheet(ws, headers, rows, widths):
    hfont = Font(name=FONT, size=9, bold=True, color='FFFFFF')
    bfont = Font(name=FONT, size=9)
    fill = PatternFill('solid', fgColor=HEADER_FILL)
    thin = Side(style='thin', color='D9D9D9')
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    ws.append(headers)
    for c in ws[1]:
        c.font, c.fill, c.border = hfont, fill, border
        c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.font, c.border = bfont, border
            c.alignment = Alignment(vertical='top', wrap_text=True)
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = 'A2'
    ws.row_dimensions[1].height = 28


def main(write):
    src = pd.read_excel(XLSX, sheet_name=SRC_SHEET)
    print(f'원본 {SRC_SHEET}: {src.shape}')
    print('사건로그 수치 대조:')
    ok = verify(src)
    for name, cols, rows, _ in SHEETS:
        print(f'  {name}: {len(rows)}행 × {len(cols)}열')
    if not ok:
        print('사건로그 수치가 데이터와 어긋납니다. 본문을 고친 뒤 다시 실행하세요.')
        sys.exit(1)
    if not write:
        print('검증만 했습니다. --write 로 파일을 갱신합니다.')
        return
    wb = openpyxl.load_workbook(XLSX)
    for name, *_ in SHEETS:
        if name in wb.sheetnames:
            del wb[name]
    for name, cols, rows, widths in SHEETS:
        ws = wb.create_sheet(name)
        style_sheet(ws, cols, rows, widths)
    # 시트 순서: 안내 → 매출데이터 → 보조 시트
    order = ['안내', SRC_SHEET] + [n for n, *_ in SHEETS if n != '안내']
    wb._sheets = [wb[n] for n in order]
    wb.active = 0
    wb.save(XLSX)
    print(f'저장: {XLSX.name} · 시트 {wb.sheetnames}')


if __name__ == '__main__':
    main('--write' in sys.argv)
