def clean(posts):
    out = []
    for board, source in SECTIONS:
        items = [p for p in posts if p["board"] == board]
        for i, p in enumerate(items):
            key = (board[0], i)
            if key not in EDITS:
                sys.exit(f"EDITS에 없는 게시물: {board} #{i} {p['headline']!r}. 제목·태그를 추가하세요.")
            title, tag, rule = EDITS[key]
            st = p["stanzas"]
            if rule == "IMAGE":
                st = IMAGE_TEXT[key]
            elif callable(rule):
                st = rule(st)
            else:
                st = st[rule:]
            st = [s for s in st if s]
            if not st:
                sys.exit(f"빈 시: {board} #{i}")
            out.append({"title": title, "tag": tag, "source": source, "stanzas": st, "permalink": p.get("permalink", "")})
    return out


def main():
    cleaned = clean(json.load(open(sys.argv[1])))
    allp = json.load(open(ALL))
    seen = {(p["source"], p["title"], p["stanzas"][0][0]) for p in allp}
    added = []
    for c in cleaned:
        if (c["source"], c["title"], c["stanzas"][0][0]) in seen:
            continue
        c = {"id": f"P{len(allp) + 1:02d}", **c, "old_section": ""}
        allp.append(c)
        added.append(c)
    json.dump(allp, open(ALL, "w"), ensure_ascii=False, indent=1)
    print(f"새로 더함 {len(added)}편, 후보 합계 {len(allp)}편")
    for c in added:
        print(c["id"], c["title"], "→ tags.tsv에 줄을 추가하고 채점할 것")


if __name__ == "__main__":
    main()
