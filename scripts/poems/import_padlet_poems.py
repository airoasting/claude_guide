def after(marker, until=None):
    """marker 연 다음부터 until로 시작하는 연 앞까지."""
    def f(st):
        i = next(k for k, s in enumerate(st) if s[0].startswith(marker))
        j = next((k for k in range(i + 1, len(st)) if until and st[k][0].startswith(until)), len(st))
        return [s for s in st[i + 1:j] if s[0] != "블랙 (시인)"]
    return f


def drop_line(st):
    return [st[0][1:]] + st[1:]


